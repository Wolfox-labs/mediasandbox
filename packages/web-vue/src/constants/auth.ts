/**
 * 这个项目**没有账号体系**。
 *
 * 后端没有用户表，`/api/*` 与 `/ws` 也没有任何鉴权——谁能连上谁就能用。
 * 前端模板（soybean-admin）自带一套登录 / 角色 / 权限守卫，直接留着会有两个后果：
 *
 *   1. 所有页面被重定向到 `/login`，**工作台根本进不去**
 *      （实测：直接打开 `/workbench/goal` 会停在登录页，界面上还印着模板的
 *      示例账号 "Soybean"）
 *   2. 那层登录门给人一种"这里有鉴权"的错觉，而它背后什么都没有
 *
 * 所以这里把它显式关掉。**这不是绕过安全，是如实反映现状。**
 *
 * 真要支持多用户时，正确顺序是：后端先加账号与鉴权（含 `/api/*` 与 WebSocket
 * 升级请求），再把这里改回 `false`，让 token 决定是否已登录。
 */
export const AUTH_DISABLED = true;
